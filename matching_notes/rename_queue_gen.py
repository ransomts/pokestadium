#!/usr/bin/env python3
"""Generate matching_notes/rename_queue.txt: src .c files still containing placeholder
symbols (func_XXXXXXXX / D_XXXXXXXX), minus files with open NON_MATCHING drafts.

Order: main-segment files first, then fragments in numeric order; wave boundaries every
--wave-size files (default 14). Re-run any time; the ledger stays the source of truth for
what has been applied.
"""
import argparse
import re
import sys
from pathlib import Path

PLACEHOLDER = re.compile(r"\b(func_[0-9A-F]{8}|D_[0-9A-F]{8})\b")
NON_MATCHING_FILES = {
    "src/33FE0.c",
    "src/4A3E0.c",
    "src/fragments/24/fragment24_1CEA00.c",
    "src/fragments/28/fragment28_2190D0.c",
    "src/fragments/62/fragment62_361050.c",
}


def sort_key(p: Path):
    rel = str(p)
    if rel.startswith("src/fragments/"):
        try:
            n = int(p.parts[2])
        except ValueError:
            n = 999
        return (1, n, rel)
    return (0, 0, rel)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--wave-size", type=int, default=14)
    args = ap.parse_args()

    files = []
    for p in sorted(Path("src").rglob("*.c")):
        rel = str(p)
        if rel in NON_MATCHING_FILES:
            continue
        text = p.read_text(errors="replace")
        n = len(PLACEHOLDER.findall(text))
        if n:
            files.append((n, rel))

    files.sort(key=lambda t: sort_key(Path(t[1])))

    out = []
    out.append("# rename wave queue (generated by matching_notes/rename_queue_gen.py)")
    out.append("# cols: placeholders_in_file<TAB>file ; '## wave N' starts each wave")
    out.append("# files with open NON_MATCHING drafts excluded; protected symbols are")
    out.append("# auto-refused by rename.py regardless.")
    wave = 0
    total = 0
    for i, (n, rel) in enumerate(files):
        if i % args.wave_size == 0:
            wave += 1
            out.append(f"## wave {wave}")
        out.append(f"{n}\t{rel}")
        total += n
    out.append(f"# total: {len(files)} files, {total} placeholder references")
    Path("matching_notes/rename_queue.txt").write_text("\n".join(out) + "\n")
    print(f"{len(files)} files, {total} placeholder refs, {wave} waves of <= {args.wave_size}")


if __name__ == "__main__":
    sys.exit(main())
